// Entrance to global settings: a gear in the site header, grouped next to the
// book and Harness entrances. Model profiles live here instead of the lab.
import { withBase } from '../../src/lib/site-path.mjs';
import { SETTINGS_PATH } from '../routes.mjs';
import { el } from './dom';
import './settings-entry.css';
// Requirement 031: the same header icon carries the update dot. Importing the
// module here keeps it injected on every page without touching integration.mjs.
import './update/update-badge';

const href = withBase(SETTINGS_PATH);
const LABEL = '设置';

function headerButton() {
  const tools = document.querySelector('.header-tools');
  if (!tools) return;
  const link = el('a', 'icon-button settings-entry');
  link.href = href;
  link.title = LABEL;
  link.setAttribute('aria-label', LABEL);
  if (location.pathname === href || location.pathname.startsWith(href)) {
    link.setAttribute('aria-current', 'page');
  }
  link.innerHTML =
    '<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><circle cx="12" cy="12" r="3"></circle><path d="M19.4 15a1.65 1.65 0 0 0 .33 1.82l.06.06a2 2 0 0 1 0 2.83 2 2 0 0 1-2.83 0l-.06-.06a1.65 1.65 0 0 0-1.82-.33 1.65 1.65 0 0 0-1 1.51V21a2 2 0 0 1-2 2 2 2 0 0 1-2-2v-.09A1.65 1.65 0 0 0 9 19.4a1.65 1.65 0 0 0-1.82.33l-.06.06a2 2 0 0 1-2.83 0 2 2 0 0 1 0-2.83l.06-.06a1.65 1.65 0 0 0 .33-1.82 1.65 1.65 0 0 0-1.51-1H3a2 2 0 0 1-2-2 2 2 0 0 1 2-2h.09A1.65 1.65 0 0 0 4.6 9a1.65 1.65 0 0 0-.33-1.82l-.06-.06a2 2 0 0 1 0-2.83 2 2 0 0 1 2.83 0l.06.06a1.65 1.65 0 0 0 1.82.33H9a1.65 1.65 0 0 0 1-1.51V3a2 2 0 0 1 2-2 2 2 0 0 1 2 2v.09a1.65 1.65 0 0 0 1 1.51 1.65 1.65 0 0 0 1.82-.33l.06-.06a2 2 0 0 1 2.83 0 2 2 0 0 1 0 2.83l-.06.06a1.65 1.65 0 0 0-.33 1.82V9a1.65 1.65 0 0 0 1.51 1H21a2 2 0 0 1 2 2 2 2 0 0 1-2 2h-.09a1.65 1.65 0 0 0-1.51 1z"></path></svg>';
  tools.prepend(link);
}

headerButton();
